#!/usr/bin/env bash
# Regenerate examples/maps/*.txt and examples/maps/README.md from the
# release binary. Run from the repository root: scripts/gen_examples.sh
set -euo pipefail

cargo build --release --quiet
BIN=target/release/rascal
OUT=examples/maps
mkdir -p "$OUT"
INDEX="$OUT/README.md"

cat > "$INDEX" <<'MD'
# Example maps

Generated by `scripts/gen_examples.sh`; each `.txt` file is the exact output
of the command shown.
MD

# example NAME "DESCRIPTION" ARGS...
example() {
    local name=$1 desc=$2
    shift 2
    "$BIN" --no-config --color=never "$@" > "$OUT/$name.txt"
    local cmd="rascal"
    for a in "$@"; do
        if [[ $a =~ [^A-Za-z0-9_./=,:-] || -z $a || $a == - ]]; then cmd+=" '$a'"; else cmd+=" $a"; fi
    done
    {
        printf '\n## %s\n\n%s\n\n```\n$ %s\n' "$name" "$desc" "$cmd"
        cat "$OUT/$name.txt"
        printf '```\n'
    } >> "$INDEX"
}

example world "The default world map." -w 100
example world-custom-chars "Your own characters for land and water." \
    -w 80 --land '#' --water '-'
example world-pacific "Centred on the Pacific, wrapping across the 180° meridian." \
    -w 100 --center 150 -s sea
example world-mercator "Mercator projection with a 30° graticule." \
    -w 100 -p mercator -g 30
example world-braille "Braille texture." -w 100 -s braille
example europe-borders "Europe with country borders and city markers." \
    europe -w 100 --border '|' -m London -m 'Paris,@' -m 41.9,12.5,X,Rome -m Berlin
example africa-blocks "Unicode block style with markers and a legend." \
    africa -w 70 -s blocks -m Cairo -m Lagos -m Nairobi -m 'Cape Town' --legend
example south-america-highlight "Highlighted countries." \
    south-america -w 60 --highlight brazil=@ --highlight 'argentina=%' --legend
example france-outline "A single country, isolated and drawn as a coastline." \
    france -w 60 -i --coast o --land ' ' -m Paris
example japan-framed "Shaded style in a rounded frame with a title." \
    japan -w 50 -s shade --frame=rounded -t Japan
example western-europe-capitals "A subregion with its capitals marked." \
    western-europe -w 80 --capitals --border ':'
example pacific-markers "The Pacific view with markers, in a double frame." \
    pacific -w 100 -f=double -t 'Pacific Rim' -m Tokyo -m Honolulu -m 'Los Angeles' -m Sydney -m Lima

echo "wrote $(ls "$OUT"/*.txt | wc -l) maps to $OUT"
